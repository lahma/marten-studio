using Microsoft.AspNetCore.Components;

using PublicApiGenerator;

namespace DataStudio.Tests;

/// <summary>
/// Snapshots the public surface of the DataStudio shell package (AGENTS.md hard rule 7, D20).
/// </summary>
/// <remarks>
/// <para>
/// The shell's public surface is its registration, its mapping, its builder and its options (v2 step 4); everything else - its services, its settings
/// seam and its endpoint mapper - is internal, and the modules reach it through <c>InternalsVisibleTo</c>. D20 keeps the components out of the
/// snapshot, so a type that appears in it and is not one of the four is a mistake rather than a feature.
/// </para>
/// <para>
/// A failure here is not automatically a bug. Run the test, open the <c>.received.txt</c> beside the <c>.verified.txt</c>, read the diff line by
/// line, say in the pull request what moved and why, and only then accept the new baseline. Never hand-edit the baseline.
/// </para>
/// </remarks>
public class PublicApiTest
{
    private static readonly System.Reflection.Assembly Shell = typeof(DataStudio.Components.StudioRoutes).Assembly;

    [Fact]
    public async Task The_public_api_has_not_changed_unintentionally()
    {
        const string header = "// Public API of DataStudio, generated by PublicApiGenerator (DataStudio.Tests.PublicApiTest); Razor components are excluded (D20)";

        await Verify(header + "\n" + PublicApi(), extension: "txt")
            .UseDirectory("Verify")
            .UseFileName("PublicApiTest_DataStudio");
    }

    /// <summary>The public types that are not components, by name, so an extra one fails with its name rather than a diff.</summary>
    [Fact]
    public void The_public_types_that_are_not_Razor_components_are_the_registration_the_mapping_the_builder_and_the_options()
    {
        Exported().Should().Equal(
            "DataStudio.DataStudioBuilder",
            "DataStudio.DataStudioEndpointRouteBuilderExtensions",
            "DataStudio.DataStudioOptions",
            "DataStudio.DataStudioServiceCollectionExtensions");
    }

    private static string[] Exported() =>
    [
        .. Shell.GetExportedTypes()
            .Where(static type => !typeof(IComponent).IsAssignableFrom(type) && type.Name != "_Imports")
            .Select(static type => type.FullName!)
            .Order(StringComparer.Ordinal),
    ];

    private static string PublicApi()
    {
        var options = new ApiGeneratorOptions
        {
            // The same generator options as the other baselines, for the same reasons.
            ExcludeAttributes =
            [
                "System.Diagnostics.DebuggerDisplayAttribute",
                "System.Reflection.AssemblyMetadataAttribute",
                "System.Runtime.CompilerServices.CompilerGeneratedAttribute",
                "System.Runtime.CompilerServices.InternalsVisibleToAttribute",
                "System.Runtime.CompilerServices.IsReadOnlyAttribute",
                "System.Runtime.CompilerServices.NullableAttribute",
                "System.Runtime.CompilerServices.NullableContextAttribute",
                "System.Runtime.CompilerServices.RefSafetyRulesAttribute",
                "System.Runtime.Versioning.TargetFrameworkAttribute",
            ],

            TreatRecordsAsClasses = false,

            // D20: Blazor components are the studio's UI, not API anyone calls; _Imports is the @using list.
            ExcludeTypes = Shell.GetExportedTypes()
                .Where(static type => typeof(IComponent).IsAssignableFrom(type) || type.Name == "_Imports")
                .ToArray(),
        };

        return Shell.GeneratePublicApi(options);
    }
}
