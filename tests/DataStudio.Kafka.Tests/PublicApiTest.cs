using System.Reflection;

using PublicApiGenerator;

namespace DataStudio.Kafka.Tests;

/// <summary>
/// Snapshots the public surface of DataStudio.Kafka.Core (AGENTS.md D36, hard rule 7): its registration types and its extension
/// points, and nothing else.
/// </summary>
/// <remarks>
/// A failure is not automatically a bug. Run the test, read the <c>.received.txt</c> beside the <c>.verified.txt</c> line by
/// line, say in the pull request what moved and why, and only then accept the new baseline. Never hand-edit it.
/// </remarks>
public class PublicApiTest
{
    private static readonly Assembly Core = Assembly.Load("DataStudio.Kafka.Core");

    private static readonly Assembly Module = typeof(KafkaDataStudioBuilderExtensions).Assembly;

    [Fact]
    public async Task The_engine_public_api_has_not_changed_unintentionally()
    {
        ApiGeneratorOptions options = Options(Core);

        const string header = "// Public API of DataStudio.Kafka.Core, generated by PublicApiGenerator (DataStudio.Kafka.Tests.PublicApiTest)";

        await Verify(header + "\n" + Core.GeneratePublicApi(options), extension: "txt")
            .UseDirectory("Verify")
            .UseFileName("PublicApiTest_DataStudioKafkaCore");
    }

    /// <summary>
    /// The engine's public types by name, so an extra one fails with its name rather than a diff. ENG-A's (decision 1.5): the options, the
    /// two builders and the key formats; ENG-B adds the decoder extension point; ENG-E the partitioner; INDEX the host's record index (D48) and the four types its one method takes and returns; D50 the diagnostics
    /// API and its read model.
    /// </summary>
    [Fact]
    public void The_public_types_are_the_registration_types_and_the_extension_points()
    {
        Core.GetExportedTypes().Select(static type => type.FullName!).Order(StringComparer.Ordinal).Should().Equal(
            "DataStudio.Kafka.IKafkaDiagnostics",
            "DataStudio.Kafka.IKafkaRecordDecoder",
            "DataStudio.Kafka.IKafkaRecordIndex",
            "DataStudio.Kafka.KafkaClusterBuilder",
            "DataStudio.Kafka.KafkaClusterStatus",
            "DataStudio.Kafka.KafkaCorrelationBuilder",
            "DataStudio.Kafka.KafkaCorrelationField",
            "DataStudio.Kafka.KafkaDecodeContext",
            "DataStudio.Kafka.KafkaDecodeResult",
            "DataStudio.Kafka.KafkaDecoders",
            "DataStudio.Kafka.KafkaEngineOptions",
            "DataStudio.Kafka.KafkaGroupMember",
            "DataStudio.Kafka.KafkaGroupPartition",
            "DataStudio.Kafka.KafkaGroupStatus",
            "DataStudio.Kafka.KafkaHeader",
            "DataStudio.Kafka.KafkaIndexAnswer",
            "DataStudio.Kafka.KafkaIndexField",
            "DataStudio.Kafka.KafkaIndexHint",
            "DataStudio.Kafka.KafkaIndexQuery",
            "DataStudio.Kafka.KafkaKeyFormat",
            "DataStudio.Kafka.KafkaMemberPlace",
            "DataStudio.Kafka.KafkaMemberState",
            "DataStudio.Kafka.KafkaPartitionOffsets",
            "DataStudio.Kafka.KafkaPartitioner",
            "DataStudio.Kafka.KafkaProfile",
            "DataStudio.Kafka.KafkaReadOutcome",
            "DataStudio.Kafka.KafkaReadProblem",
            "DataStudio.Kafka.KafkaRedactionBuilder",
            "DataStudio.Kafka.KafkaRedactionRule",
            "DataStudio.Kafka.KafkaScanLimits",
            "DataStudio.Kafka.KafkaTopicBuilder",
            "DataStudio.Kafka.KafkaTopicPartition",
            "DataStudio.Kafka.KafkaTopicPresence",
            "DataStudio.Kafka.KafkaTopicStatus");
    }

    /// <summary>
    /// The public surface of the Kafka module itself (D34, D35, hard rule 7): one static class, two classes and one record. Components are
    /// excluded by the generator (D20), and every seam the shell grew for the module is internal.
    /// </summary>
    [Fact]
    public async Task The_module_public_api_has_not_changed_unintentionally()
    {
        const string header = "// Public API of DataStudio.Kafka, generated by PublicApiGenerator (DataStudio.Kafka.Tests.PublicApiTest)";

        await Verify(header + "\n" + Module.GeneratePublicApi(Options(Module)), extension: "txt")
            .UseDirectory("Verify")
            .UseFileName("PublicApiTest_DataStudioKafka");
    }

    /// <summary>The module's public types by name, so an extra one fails with its name rather than a diff. Components are not counted (D20).</summary>
    [Fact]
    public void The_public_types_are_exactly_these_four()
    {
        Module.GetExportedTypes()
            .Where(static type => !typeof(Microsoft.AspNetCore.Components.IComponent).IsAssignableFrom(type) && type.Name != "_Imports")
            .Select(static type => type.FullName!)
            .Order(StringComparer.Ordinal)
            .Should().Equal(
                "DataStudio.Kafka.KafkaCapabilities",
                "DataStudio.Kafka.KafkaOptions",
                "DataStudio.Kafka.KafkaTopicResource",
                "DataStudio.KafkaDataStudioBuilderExtensions");
    }

    private static ApiGeneratorOptions Options(Assembly assembly) => new()
    {
        // The same generator options as the other baselines, for the same reasons.
        ExcludeAttributes =
        [
            "System.Diagnostics.DebuggerDisplayAttribute",
            "System.Reflection.AssemblyMetadataAttribute",
            "System.Runtime.CompilerServices.CompilerGeneratedAttribute",
            "System.Runtime.CompilerServices.InternalsVisibleToAttribute",
            "System.Runtime.CompilerServices.IsReadOnlyAttribute",
            "System.Runtime.CompilerServices.NullableAttribute",
            "System.Runtime.CompilerServices.NullableContextAttribute",
            "System.Runtime.CompilerServices.RefSafetyRulesAttribute",
            "System.Runtime.Versioning.TargetFrameworkAttribute",
        ],

        TreatRecordsAsClasses = false,

        // D20: Blazor components are the studio's UI, not API anyone calls; _Imports is the @using list.
        ExcludeTypes = assembly.GetExportedTypes()
            .Where(static type => typeof(Microsoft.AspNetCore.Components.IComponent).IsAssignableFrom(type) || type.Name == "_Imports")
            .ToArray(),
    };
}
