using System.Reflection;

using KStudio;

using PublicApiGenerator;

namespace KStudioWolverine.Tests;

/// <summary>
/// Snapshots the public surface of KStudio.Wolverine (AGENTS.md D43, hard rule 7): one static class and one class, and nothing else. Every seam it
/// uses in KStudio.Core is internal.
/// </summary>
/// <remarks>
/// A failure is not automatically a bug. Run the test, read the <c>.received.txt</c> beside the <c>.verified.txt</c> line by line, say in the pull
/// request what moved and why, and only then accept the new baseline. Never hand-edit it.
/// </remarks>
public class PublicApiTest
{
    private static readonly Assembly Adapter = typeof(KafkaWolverineExtensions).Assembly;

    [Fact]
    public async Task The_adapter_public_api_has_not_changed_unintentionally()
    {
        const string header = "// Public API of KStudio.Wolverine, generated by PublicApiGenerator (KStudioWolverine.Tests.PublicApiTest)";

        await Verify(header + "\n" + Adapter.GeneratePublicApi(Options()), extension: "txt")
            .UseDirectory("Verify")
            .UseFileName("PublicApiTest_KStudioWolverine");
    }

    /// <summary>The public types by name, so an extra one fails with its name rather than a diff.</summary>
    [Fact]
    public void The_public_types_are_exactly_these_two()
    {
        Adapter.GetExportedTypes().Select(static type => type.FullName!).Order(StringComparer.Ordinal).Should().Equal(
            "KStudio.KafkaWolverineExtensions",
            "KStudio.KafkaWolverineOptions");
    }

    private static ApiGeneratorOptions Options() => new()
    {
        // The same generator options as the other baselines, for the same reasons.
        ExcludeAttributes =
        [
            "System.Diagnostics.DebuggerDisplayAttribute",
            "System.Reflection.AssemblyMetadataAttribute",
            "System.Runtime.CompilerServices.CompilerGeneratedAttribute",
            "System.Runtime.CompilerServices.InternalsVisibleToAttribute",
            "System.Runtime.CompilerServices.IsReadOnlyAttribute",
            "System.Runtime.CompilerServices.NullableAttribute",
            "System.Runtime.CompilerServices.NullableContextAttribute",
            "System.Runtime.CompilerServices.RefSafetyRulesAttribute",
            "System.Runtime.Versioning.TargetFrameworkAttribute",
        ],

        TreatRecordsAsClasses = false,
    };
}
