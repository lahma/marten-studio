namespace MartenStudio.Tests.Conventions;

/// <summary>
/// Asserts that the four GitHub Actions workflows are the generated ones, and that each still carries
/// the handful of lines its job actually depends on.
/// </summary>
/// <remarks>
/// <para>
/// All four files are generated from the <c>[GitHubActions]</c> attributes in
/// <c>build/Build.CI.GitHubActions.cs</c> (AGENTS.md hard rule 2). Nothing in the build ever reads them
/// back, so without this test a hand-edit would survive until the next build silently overwrote it - and
/// a wrong permission or a missing token would only be discovered by a release that failed.
/// </para>
/// <para>
/// The assertions are deliberately about <em>capability</em>, not formatting: that the key-minting job
/// has <c>id-token: write</c> and only <c>contents: read</c>, that the release job has the repository
/// write it needs and the token to use it, that the two CI jobs cache the Playwright browsers and can
/// write nothing, that the latest leg really asks for the latest Marten and the latest Npgsql, and that the
/// floor leg and the publish leg ask for neither. A reformat of the generator's YAML must not fail this
/// test; a change to who can do what must.
/// </para>
/// </remarks>
public class WorkflowGenerationTests
{
    private const string GeneratedHeaderFirstLine =
        "# ------------------------------------------------------------------------------";

    /// <summary>The one workflow file a nuget.org trusted publishing policy may name.</summary>
    private const string PublishWorkflow = "publish.yml";

    /// <summary>The permission a workflow needs to ask GitHub for an OIDC token, in any form.</summary>
    private const string IdToken = "id-token";

    private static string WorkflowsDirectory => RepositoryRoot.Combine(".github", "workflows");

    [Theory]
    [InlineData("build.yml")]
    [InlineData("marten-latest.yml")]
    [InlineData("publish.yml")]
    [InlineData("release.yml")]
    public void Every_workflow_this_repository_needs_exists(string fileName)
    {
        File.Exists(Path.Combine(WorkflowsDirectory, fileName)).Should().BeTrue(
            $"{fileName} is generated from a [GitHubActions] attribute; run `dotnet fallout Test` and commit it");
    }

    /// <summary>
    /// Every <c>.yml</c> <em>and</em> <c>.yaml</c> file in the workflows directory carries the header
    /// Fallout writes. GitHub runs both extensions, so a hand-written <c>.yaml</c> would be a workflow
    /// this check never looked at.
    /// </summary>
    [Fact]
    public void Every_workflow_file_is_generated_and_none_is_hand_written()
    {
        WorkflowFilesIn(WorkflowsDirectory).Should().NotBeEmpty();

        HandWrittenWorkflows(WorkflowsDirectory).Should().BeEmpty(
            "every workflow in this repository comes from a [GitHubActions] attribute and starts with the " +
            "generated header - a rule line, then the <auto-generated> marker");
    }

    /// <summary>
    /// Anti-vacuity for the check above: it finds a hand-written file under either extension, passes a
    /// generated one, and ignores a file GitHub would not run.
    /// </summary>
    [Fact]
    public void The_generated_check_catches_a_hand_written_workflow_under_either_extension()
    {
        var directory = NewScratchDirectory();

        try
        {
            WriteFile(directory, "generated.yml",
                GeneratedHeaderFirstLine, "# <auto-generated>", "# </auto-generated>", GeneratedHeaderFirstLine, "name: generated");
            WriteFile(directory, "hand.yaml", "name: hand", "on: push");
            WriteFile(directory, "header-only.yml", GeneratedHeaderFirstLine, "name: half");
            WriteFile(directory, "notes.txt", "name: not a workflow");

            WorkflowFilesIn(directory).Select(x => Path.GetFileName(x))
                .Should().BeEquivalentTo("generated.yml", "hand.yaml", "header-only.yml");
            HandWrittenWorkflows(directory).Should().BeEquivalentTo("hand.yaml", "header-only.yml");
        }
        finally
        {
            Directory.Delete(directory, recursive: true);
        }
    }

    /// <summary>
    /// The publish job is the only one that can mint a nuget.org key, so it must hold the OIDC permission
    /// and <em>only</em> read access to the repository.
    /// </summary>
    [Fact]
    public void The_publish_workflow_can_mint_a_key_and_cannot_write_to_the_repository()
    {
        var publish = ReadWorkflow("publish.yml");

        publish.Should().Contain("id-token: write");
        publish.Should().Contain("contents: read");
        publish.Should().NotContain("contents: write",
            "the workflow a nuget.org trusted publishing policy names must never also hold repository write");

        publish.Should().Contain("environment: nuget",
            "the GitHub environment is a second claim the trusted publishing policy matches on");
        publish.Should().Contain("NUGET_USER: lahma",
            "the policy owner's nuget.org profile name is public and travels as a plain env value");

        publish.Should().Contain("tags:");
        publish.Should().Contain("v*.*.*", "only a version tag may start the job that can mint a key");
        publish.Should().NotContain("paths:",
            "a path filter next to tags: evaluates over the tag commit's diff and can silently skip the run");
    }

    /// <summary>
    /// The release job writes the GitHub Release, so it needs repository write and the token to use it -
    /// and it must not be able to mint a publishing key.
    /// </summary>
    [Fact]
    public void The_release_workflow_can_write_releases_and_cannot_mint_a_key()
    {
        var release = ReadWorkflow("release.yml");

        release.Should().Contain("contents: write");
        release.Should().Contain("GITHUB_TOKEN: ${{ secrets.GITHUB_TOKEN }}",
            "EnableGitHubToken is what lets ICreateGitHubRelease authenticate against the GitHub API");
        release.Should().NotContain("id-token: write",
            "the workflow that holds repository write must never also be able to mint a nuget.org key");
        release.Should().Contain("v*.*.*");
    }

    [Theory]
    [InlineData("build.yml")]
    [InlineData("marten-latest.yml")]
    public void The_ci_workflows_cache_the_playwright_browsers(string fileName)
    {
        var ci = ReadWorkflow(fileName);

        ci.Should().Contain("~/.cache/ms-playwright",
            "a Chromium download is ~150 MB and would otherwise be paid on every push and pull request");
        ci.Should().Contain("~/.nuget/packages");
        ci.Should().Contain("cancel-in-progress: true");
    }

    /// <summary>
    /// The CI workflows run on every push and every pull request, including from a fork. They must not be
    /// able to mint a nuget.org publishing key, and they must not be able to write to the repository.
    /// </summary>
    [Theory]
    [InlineData("build.yml")]
    [InlineData("marten-latest.yml")]
    public void The_ci_workflows_can_neither_mint_a_key_nor_write_to_the_repository(string fileName)
    {
        var ci = ReadWorkflow(fileName);

        ci.Should().NotContain("id-token: write",
            "only publish.yml may hold the OIDC permission; a workflow that runs on every pull request must not");
        ci.Should().NotContain("contents: write");
        ci.Should().Contain("contents: read",
            "naming one read permission makes every other permission 'none' for the run");
        ci.Should().NotContain("environment:",
            "the nuget environment is a claim the trusted publishing policy matches on; only publish.yml names it");
        ci.Should().NotContain("secrets.",
            "a workflow that runs for a fork's pull request has no business importing a secret");
    }

    /// <summary>
    /// The CI workflows' permissions are exactly <c>contents: read</c>: one block, at the workflow level,
    /// with that one entry. Ruling out <c>contents: write</c> is not the same thing - a
    /// <c>pull-requests: write</c>, a <c>write-all</c> or a job-level block would all have passed it.
    /// </summary>
    [Theory]
    [InlineData("build.yml")]
    [InlineData("marten-latest.yml")]
    public void The_ci_workflows_hold_exactly_contents_read(string fileName)
    {
        PermissionsProblem(ReadWorkflowLines(fileName)).Should().BeNull(
            $"{fileName} runs on every push and pull request, and naming exactly one read permission is what " +
            "makes every other permission 'none' for the run");
    }

    /// <summary>
    /// Anti-vacuity for the check above: it passes exactly <c>contents: read</c> and refuses every
    /// near miss.
    /// </summary>
    [Theory]
    [InlineData("permissions:\n  contents: read\n\njobs:\n  a:\n    runs-on: ubuntu-latest", true)]
    [InlineData("permissions:\n  contents: read\n  pull-requests: write\n\njobs:\n  a:\n    runs-on: ubuntu-latest", false)]
    [InlineData("permissions:\n  contents: write\n\njobs:\n  a:\n    runs-on: ubuntu-latest", false)]
    [InlineData("permissions:\n  contents: read\n\njobs:\n  a:\n    permissions:\n      id-token: write\n    runs-on: ubuntu-latest", false)]
    [InlineData("permissions: write-all\n\njobs:\n  a:\n    runs-on: ubuntu-latest", false)]
    [InlineData("jobs:\n  a:\n    permissions:\n      contents: read\n    runs-on: ubuntu-latest", false)]
    [InlineData("name: none\n\njobs:\n  a:\n    runs-on: ubuntu-latest", false)]
    public void The_permissions_check_refuses_anything_but_exactly_contents_read(string yaml, bool readOnly)
    {
        var problem = PermissionsProblem(yaml.Split('\n'));

        if (readOnly)
        {
            problem.Should().BeNull();
        }
        else
        {
            problem.Should().NotBeNull();
        }
    }

    /// <summary>
    /// Whatever file is added next, the only one that can ask GitHub for an OIDC token is the one the
    /// nuget.org policy names. Checked over every <c>.yml</c> and <c>.yaml</c> file on disk rather than a
    /// list, so a fifth workflow is covered the moment it is generated.
    /// </summary>
    [Fact]
    public void Only_the_publish_workflow_can_mint_a_key()
    {
        WorkflowFilesIn(WorkflowsDirectory).Select(x => Path.GetFileName(x)).Should().Contain(PublishWorkflow);

        // The scan has to be able to see the thing it is looking for: publish.yml holds it.
        ReadWorkflow(PublishWorkflow).Should().Contain(IdToken);

        WorkflowsThatCanMintAKey(WorkflowsDirectory).Should().BeEmpty(
            "no file but publish.yml is the one the nuget.org trusted publishing policy names, and the one " +
            "workflow that can mint a key must stay the only one");
    }

    /// <summary>
    /// Anti-vacuity for the check above: a second file that asks for an OIDC token is found under either
    /// extension, and publish.yml itself is not reported.
    /// </summary>
    [Fact]
    public void The_key_minting_check_finds_a_second_minter_under_either_extension()
    {
        var directory = NewScratchDirectory();

        try
        {
            WriteFile(directory, PublishWorkflow, "permissions:", "  id-token: write");
            WriteFile(directory, "rogue.yaml", "jobs:", "  a:", "    permissions:", "      id-token: write");
            WriteFile(directory, "rogue.yml", "permissions:", "  id-token: write");
            WriteFile(directory, "fine.yml", "permissions:", "  contents: read");

            WorkflowsThatCanMintAKey(directory).Should().BeEquivalentTo("rogue.yaml", "rogue.yml");
        }
        finally
        {
            Directory.Delete(directory, recursive: true);
        }
    }

    /// <summary>
    /// The latest-Marten leg is build.yml's run with one difference that matters: it asks Fallout for the
    /// latest-tested Marten. If the env line went missing it would silently test the floor a second time,
    /// which is a green check that proves nothing.
    /// </summary>
    [Fact]
    public void The_marten_latest_workflow_runs_both_suites_at_the_latest_tested_marten()
    {
        var latest = ReadWorkflow("marten-latest.yml");
        var lines = ReadWorkflowLines("marten-latest.yml");

        latest.Should().Contain("MARTEN_VERSION: latest",
            "Fallout binds MARTEN_VERSION to the MartenVersion parameter, and 'latest' resolves to " +
            "MartenStudioMartenLatest in Directory.Packages.props (build/Build.Marten.cs)");

        // The same triggers as build.yml: every push and every pull request to main.
        latest.Should().Contain("push:");
        latest.Should().Contain("pull_request:");
        latest.Should().Contain("- main");

        // Test runs both suites (Test depends on Browsers, which installs Chromium on CI), and nothing on
        // this leg packs or publishes: Pack refuses any Marten but the floor in any case.
        lines.Select(x => x.Trim())
            .Where(x => x.StartsWith("run: dotnet fallout", StringComparison.Ordinal))
            .Should().ContainSingle()
            .Which.Should().Be("run: dotnet fallout Test");
    }

    /// <summary>
    /// The latest leg also runs PostgresStudio's projects at the latest-tested Npgsql. Without the env line the
    /// second pass over <c>postgres-studio.slnf</c> never runs, and nothing would say so: PostgresStudio would be
    /// tested only at its floor while a host without Marten is on Npgsql 10.
    /// </summary>
    [Fact]
    public void The_marten_latest_workflow_also_runs_PostgresStudio_at_the_latest_tested_npgsql()
    {
        var latest = ReadWorkflow("marten-latest.yml");

        latest.Should().Contain("NPGSQL_VERSION: latest",
            "Fallout binds NPGSQL_VERSION to the NpgsqlVersion parameter, and 'latest' resolves to " +
            "PostgresStudioNpgsqlLatest in Directory.Packages.props and adds the pass over postgres-studio.slnf " +
            "(build/Build.Npgsql.cs)");
        latest.Should().Contain("MARTEN_VERSION: latest", "one workflow runs both latest legs");
    }

    /// <summary>
    /// The floor workflows ask for no other version. <c>build.yml</c> is the floor leg - a <c>MARTEN_VERSION</c> or
    /// <c>NPGSQL_VERSION</c> there would leave the floors the packages ship with untested - and <c>publish.yml</c>
    /// packs, which refuses anything but the floors.
    /// </summary>
    [Theory]
    [InlineData("build.yml")]
    [InlineData("publish.yml")]
    public void The_floor_workflows_ask_for_neither_the_latest_marten_nor_the_latest_npgsql(string fileName)
    {
        var workflow = ReadWorkflow(fileName);

        workflow.Should().NotContain("MARTEN_VERSION", "this workflow runs at the Marten floor");
        workflow.Should().NotContain("NPGSQL_VERSION", "this workflow runs at the Npgsql floor");
    }

    /// <summary>
    /// The two CI workflows must not share a cache key. actions/cache never overwrites a key that exists,
    /// so with one key between them whichever finished first would save it and the other would restore a
    /// cache without its own Marten's packages on every run.
    /// </summary>
    [Fact]
    public void The_two_ci_workflows_do_not_share_a_cache_key()
    {
        static string CacheKey(string fileName) =>
            ReadWorkflowLines(fileName).Single(x => x.TrimStart().StartsWith("key:", StringComparison.Ordinal)).Trim();

        var build = CacheKey("build.yml");
        var latest = CacheKey("marten-latest.yml");

        latest.Should().NotBe(build);
        latest.Should().Contain("marten-latest.yml");
    }

    /// <summary>
    /// The nuget.org leg is one job running one target chain. More jobs would mean more OIDC exchanges
    /// racing the one-key-per-30-seconds rate limit, and a Publish that did not follow a Test in the same
    /// run would be publishing something nothing had verified.
    /// </summary>
    [Fact]
    public void The_publish_workflow_runs_compile_test_pack_and_publish_in_one_job()
    {
        var publish = ReadWorkflow("publish.yml");

        publish.Should().Contain("Compile Test Pack Publish");
    }

    private static string ReadWorkflow(string fileName) =>
        File.ReadAllText(Path.Combine(WorkflowsDirectory, fileName));

    private static string[] ReadWorkflowLines(string fileName) =>
        File.ReadAllLines(Path.Combine(WorkflowsDirectory, fileName));

    /// <summary>Every file GitHub would run as a workflow: both extensions, nothing else.</summary>
    private static string[] WorkflowFilesIn(string directory) =>
        Directory.EnumerateFiles(directory)
            .Where(x => Path.GetExtension(x).Equals(".yml", StringComparison.OrdinalIgnoreCase)
                || Path.GetExtension(x).Equals(".yaml", StringComparison.OrdinalIgnoreCase))
            .Order(StringComparer.Ordinal)
            .ToArray();

    /// <summary>The workflow files that do not start with Fallout's generated header.</summary>
    private static string[] HandWrittenWorkflows(string directory) =>
        WorkflowFilesIn(directory)
            .Where(x => !IsGenerated(File.ReadAllLines(x)))
            .Select(x => Path.GetFileName(x))
            .ToArray();

    /// <summary>The workflow files other than publish.yml that mention an OIDC token at all.</summary>
    private static string[] WorkflowsThatCanMintAKey(string directory) =>
        WorkflowFilesIn(directory)
            .Where(x => !string.Equals(Path.GetFileName(x), PublishWorkflow, StringComparison.Ordinal))
            .Where(x => File.ReadAllText(x).Contains(IdToken, StringComparison.Ordinal))
            .Select(x => Path.GetFileName(x))
            .ToArray();

    /// <summary>The header Fallout writes: a rule line first, and the <c>&lt;auto-generated&gt;</c> marker.</summary>
    private static bool IsGenerated(string[] lines) =>
        lines.Length > 0
        && lines[0] == GeneratedHeaderFirstLine
        && lines.Any(x => x.Contains("<auto-generated>", StringComparison.Ordinal));

    /// <summary>
    /// Why a workflow's permissions are not exactly <c>contents: read</c>, or <see langword="null" /> when
    /// they are: one <c>permissions:</c> block, at the workflow level, holding that one entry.
    /// </summary>
    /// <remarks>
    /// A block is the <c>permissions:</c> line plus every following line indented deeper than it; an
    /// inline value (<c>permissions: write-all</c>, <c>permissions: {}</c>) is an entry of its own. A
    /// job-level block counts as a second block, because it replaces the workflow's for that job.
    /// </remarks>
    private static string? PermissionsProblem(string[] lines)
    {
        const string Key = "permissions:";
        var blocks = new List<(int Indent, List<string> Entries)>();

        for (var i = 0; i < lines.Length; i++)
        {
            var line = lines[i].TrimEnd('\r');
            var trimmed = line.TrimStart();

            if (!trimmed.StartsWith(Key, StringComparison.Ordinal))
            {
                continue;
            }

            var indent = line.Length - trimmed.Length;
            var entries = new List<string>();
            var inline = trimmed[Key.Length..].Trim();

            if (inline.Length > 0)
            {
                entries.Add(inline);
            }

            for (var j = i + 1; j < lines.Length; j++)
            {
                var next = lines[j].TrimEnd('\r');

                if (string.IsNullOrWhiteSpace(next))
                {
                    continue;
                }

                if (next.Length - next.TrimStart().Length <= indent)
                {
                    break;
                }

                entries.Add(next.Trim());
            }

            blocks.Add((indent, entries));
        }

        if (blocks.Count == 0)
        {
            return "there is no permissions: block, so the repository default - which may be read-write - applies";
        }

        if (blocks.Count > 1)
        {
            return $"there are {blocks.Count} permissions: blocks, and a job-level one replaces the workflow's for that job";
        }

        var (blockIndent, blockEntries) = blocks[0];

        if (blockIndent != 0)
        {
            return "the only permissions: block is a job's, so the workflow itself takes the repository default";
        }

        return blockEntries is ["contents: read"]
            ? null
            : $"the permissions are [{string.Join(", ", blockEntries)}], not exactly contents: read";
    }

    private static void WriteFile(string directory, string name, params string[] lines) =>
        File.WriteAllLines(Path.Combine(directory, name), lines);

    private static string NewScratchDirectory()
    {
        var path = Path.Combine(Path.GetTempPath(), "marten-studio-workflow-tests", Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(path);
        return path;
    }
}
