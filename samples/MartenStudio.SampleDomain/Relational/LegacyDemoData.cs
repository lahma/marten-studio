    /// <summary>
    /// Twelve messages: JSON payloads, three bodies well over the TOAST threshold, and attachments that
    /// are JSON, gzip, a PNG header, CSV text or nothing - the cases a bytea preview has to tell apart.
    /// </summary>
    private static async Task<int> SeedIntegrationMessagesAsync(
        NpgsqlConnection connection,
        NpgsqlTransaction transaction,
        CancellationToken cancellationToken)
    {
        if (await DemoTable.HasRowsAsync(connection, transaction, RelationalDemoSchema.LegacySchemaName, "integration_messages", cancellationToken)
                .ConfigureAwait(false))
        {
            return 0;
        }

        bool hasSender;
        await using (var probe = new NpgsqlCommand(
            """
            select exists (select 1 from pg_catalog.pg_attribute
                           where attrelid = 'legacy.integration_messages'::regclass
                             and attname = 'sender' and not attisdropped)
            """,
            connection,
            transaction))
        {
            hasSender = await probe.ExecuteScalarAsync(cancellationToken).ConfigureAwait(false) is true;
        }

        string sql = hasSender
            ? """
              insert into legacy.integration_messages
                (message_id, channel, payload, raw_body, attachment, received_at, sent_at_local, sender)
              values (@id, @channel, @payload, @body, @attachment, @received, @sent, @sender)
              """
            : """
              insert into legacy.integration_messages
                (message_id, channel, payload, raw_body, attachment, received_at, sent_at_local)
              values (@id, @channel, @payload, @body, @attachment, @received, @sent)
              """;

        await using var batch = new NpgsqlBatch(connection, transaction);

        DateTime receivedBase = new(2026, 9, 20, 6, 0, 0, DateTimeKind.Utc);

        for (int i = 1; i <= 12; i++)
        {
            string channel = Channels[i % Channels.Length];
            string partner = Partners[i % Partners.Length];
            DateTime received = receivedBase.AddMinutes(i * 97);

            var command = new NpgsqlBatchCommand(sql);

            command.Parameters.Add(new NpgsqlParameter("id", NpgsqlDbType.Uuid)
            {
                Value = new Guid(string.Create(CultureInfo.InvariantCulture, $"6c1e5a70-0d0c-4b1a-9e5f-{i:000000000000}")),
            });
            command.Parameters.Add(new NpgsqlParameter("channel", NpgsqlDbType.Text) { Value = channel });
            command.Parameters.Add(new NpgsqlParameter("payload", NpgsqlDbType.Jsonb) { Value = Payload(i, channel, partner) });
            command.Parameters.Add(new NpgsqlParameter("body", NpgsqlDbType.Text) { Value = (object?) RawBody(i, partner) ?? DBNull.Value });
            command.Parameters.Add(new NpgsqlParameter("attachment", NpgsqlDbType.Bytea) { Value = (object?) Attachment(i, partner) ?? DBNull.Value });
            command.Parameters.Add(new NpgsqlParameter("received", NpgsqlDbType.TimestampTz) { Value = received });

            // timestamp without time zone: the sender's wall clock, three hours ahead of UTC, and never
            // converted - some partners do not send one at all.
            command.Parameters.Add(new NpgsqlParameter("sent", NpgsqlDbType.Timestamp)
            {
                Value = i % 4 == 0
                    ? DBNull.Value
                    : DateTime.SpecifyKind(received.AddHours(3).AddMinutes(-2), DateTimeKind.Unspecified),
            });

            if (hasSender)
            {
                // Mixed case on purpose: it is the column type that makes Orders@ and orders@ one sender.
                command.Parameters.Add(new NpgsqlParameter("sender", NpgsqlDbType.Text)
                {
                    Value = (i % 2 == 0 ? "Orders@" : "orders@") + partner.Split(' ')[0] + ".example",
                });
            }

            batch.BatchCommands.Add(command);
        }

        return await batch.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);
    }

    private static string Payload(int i, string channel, string partner)
    {
        // Three dollars, so that JSON's own "}}" is content rather than the end of a hole.
        string lines = string.Join(
            ",",
            Enumerable.Range(1, 1 + (i % 4)).Select(n => string.Create(
                CultureInfo.InvariantCulture,
                $$$"""{"line":{{{n}}},"sku":"SKU-{{{(i + n) % 20 + 1:000}}}","quantity":{{{(i * n) % 9 + 1}}}}""")));

        string type = i % 3 == 0 ? "DESADV" : "ORDERS";
        string acknowledged = i % 5 != 0 ? "true" : "false";

        return string.Create(
            CultureInfo.InvariantCulture,
            $$$"""{"type":"{{{type}}}","channel":"{{{channel}}}","partner":"{{{partner}}}","sequence":{{{1000 + i}}},"acknowledged":{{{acknowledged}}},"lines":[{{{lines}}}],"meta":{"retries":{{{i % 3}}},"schema":"v2"}}""");
    }

    /// <summary>
    /// An EDIFACT-shaped body: a few hundred characters for most messages, and 12, 24 and 48 KB for three
    /// of them, so that a cell has to be cut on the server rather than streamed whole.
    /// </summary>
    private static string? RawBody(int i, string partner)
    {
        if (i == 5)
        {
            return null;
        }

        int target = i switch
        {
            3 => 12 * 1024,
            7 => 24 * 1024,
            11 => 48 * 1024,
            _ => 300,
        };

        var body = new StringBuilder();
        body.Append(CultureInfo.InvariantCulture, $"UNB+UNOC:3+{partner.Split(' ')[0].ToUpperInvariant()}:ZZ+ACME:ZZ+260920:0600+{i:00000}'");

        for (int n = 1; body.Length < target; n++)
        {
            body.Append(CultureInfo.InvariantCulture, $"\nLIN+{n}++SKU-{(n * 7 + i) % 20 + 1:000}:SA'QTY+21:{(n * i) % 40 + 1}'PRI+AAA:{4.5m + ((n * 13) % 200 / 4m):0.00}'");
        }

        body.Append(CultureInfo.InvariantCulture, $"\nUNZ+1+{i:00000}'");

        return body.ToString();
    }

    private static byte[]? Attachment(int i, string partner)
    {
        switch (i % 5)
        {
            case 1:
                return Encoding.UTF8.GetBytes(string.Create(
                    CultureInfo.InvariantCulture,
                    $$"""{"ack":"{{i:0000}}","partner":"{{partner}}","status":"accepted"}"""));

            case 2:
                using (var buffer = new MemoryStream())
                {
                    using (var gzip = new GZipStream(buffer, CompressionLevel.SmallestSize, leaveOpen: true))
                    {
                        byte[] text = Encoding.UTF8.GetBytes(string.Concat(Enumerable.Repeat("sku;quantity;warehouse\n", 40)));
                        gzip.Write(text);
                    }

                    return buffer.ToArray();
                }

            case 3:
                // A PNG signature and the start of an IHDR chunk: enough for a sniffer to say "image/png".
                return [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
                    0x00, 0x00, 0x00, 0x40, 0x00, 0x00, 0x00, 0x40, 0x08, 0x06, 0x00, 0x00, 0x00, (byte) i];

            case 4:
                return Encoding.UTF8.GetBytes("sku;quantity\nSKU-001;4\nSKU-002;12\nSKU-017;1\n");

            default:
                return null;
        }
    }

    /// <summary>
    /// A credit line for most of the seeded Marten customers - not all, so that "referenced by nothing"
    /// is a state the demo has too. Only customers that exist in <c>mt_doc_customer</c> get one.
    /// </summary>
    private static async Task<int> SeedCustomerCreditAsync(
        NpgsqlConnection connection,
        NpgsqlTransaction transaction,
        CancellationToken cancellationToken)
    {
        if (!await DemoTable.ExistsAsync(connection, transaction, RelationalDemoSchema.MartenDocumentSchemaName, "mt_doc_customer", cancellationToken)
                .ConfigureAwait(false)
            || await DemoTable.HasRowsAsync(connection, transaction, RelationalDemoSchema.LegacySchemaName, RelationalDemoSchema.CustomerCreditTable, cancellationToken)
                .ConfigureAwait(false))
        {
            return 0;
        }

        List<Guid> ids = [];
        List<decimal> limits = [];
        List<string> currencies = [];
        List<string> bands = [];
        List<DateTime> reviewed = [];

        for (int i = 1; i <= SampleDataSeeder.CustomerCount; i++)
        {
            if (i % 4 == 0)
            {
                continue;
            }

            ids.Add(SampleDataSeeder.CustomerId(i));
            limits.Add(1_000m * (2 + (i * 7 % 23)));
            currencies.Add(i % 6 == 0 ? "SEK" : "EUR");
            bands.Add(RiskBands[i % RiskBands.Length]);
            reviewed.Add(new DateTime(2026, 4, 1, 9, 0, 0, DateTimeKind.Utc).AddDays(i * 5));
        }

        await using var command = new NpgsqlCommand(
            """
            insert into legacy.customer_credit (customer_id, credit_limit, currency, risk_band, reviewed_at)
            select x.id, x.credit_limit, x.currency, x.risk_band, x.reviewed_at
            from unnest(@ids, @limits, @currencies, @bands, @reviewed)
                   as x(id, credit_limit, currency, risk_band, reviewed_at)
            where exists (select 1 from studio_sample.mt_doc_customer c where c.id = x.id)
            """,
            connection,
            transaction);

        command.Parameters.Add(new NpgsqlParameter("ids", NpgsqlDbType.Array | NpgsqlDbType.Uuid) { Value = ids.ToArray() });
        command.Parameters.Add(new NpgsqlParameter("limits", NpgsqlDbType.Array | NpgsqlDbType.Numeric) { Value = limits.ToArray() });
        command.Parameters.Add(new NpgsqlParameter("currencies", NpgsqlDbType.Array | NpgsqlDbType.Text) { Value = currencies.ToArray() });
        command.Parameters.Add(new NpgsqlParameter("bands", NpgsqlDbType.Array | NpgsqlDbType.Text) { Value = bands.ToArray() });
        command.Parameters.Add(new NpgsqlParameter("reviewed", NpgsqlDbType.Array | NpgsqlDbType.TimestampTz) { Value = reviewed.ToArray() });

        return await command.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);
    }

    private static async Task<int> SeedAppSettingsAsync(
        NpgsqlConnection connection,
        NpgsqlTransaction transaction,
        CancellationToken cancellationToken)
    {
        if (!await DemoTable.ExistsAsync(connection, transaction, RelationalDemoSchema.MartenDocumentSchemaName, RelationalDemoSchema.AppSettingsTable, cancellationToken)
                .ConfigureAwait(false)
            || await DemoTable.HasRowsAsync(connection, transaction, RelationalDemoSchema.MartenDocumentSchemaName, RelationalDemoSchema.AppSettingsTable, cancellationToken)
                .ConfigureAwait(false))
        {
            return 0;
        }

        return await ExecuteAsync(connection, transaction, AppSettings, cancellationToken).ConfigureAwait(false);
    }

