/// <summary>
/// The rows of the <c>legacy</c> schema, of <c>legacy.customer_credit</c>'s link to the Marten customers,
/// and of <c>studio_sample.app_settings</c>.
/// </summary>
/// <remarks>
/// <para>
/// <b>Table by table, each only when it is empty.</b> A table that already has rows is somebody's -
/// the previous start's, or a developer's edit - and is left alone. A table that is empty is filled,
/// which is also how <c>legacy.customer_credit</c> comes back after Marten's re-seed truncated
/// <c>mt_doc_customer</c> with <c>CASCADE</c> and took it along. Parents are filled before children,
/// so a foreign key is never checked against a table that has not been written yet.
/// </para>
/// <para>
/// <b>Deterministic.</b> Every value is a function of a row number, generated by Postgres from
/// <c>generate_series</c> where it can be and by the few lines of C# below where it cannot (gzip bytes,
/// the Marten customer ids). Two runs of the demo describe the same data, so a screenshot stays true.
/// </para>
/// </remarks>
internal static class LegacyDemoData
{
    /// <summary>Fills every empty demo table.</summary>
    /// <returns>How many rows were written.</returns>
    internal static async Task<int> SeedAsync(
        NpgsqlConnection connection,
        NpgsqlTransaction transaction,
        CancellationToken cancellationToken)
    {
        int rows = 0;

        rows += await SeedWhenEmptyAsync(connection, transaction, "departments", Departments, cancellationToken).ConfigureAwait(false);
        rows += await SeedWhenEmptyAsync(connection, transaction, "employees", Employees, cancellationToken).ConfigureAwait(false);
        rows += await SeedWhenEmptyAsync(connection, transaction, "product_catalogue", ProductCatalogue, cancellationToken).ConfigureAwait(false);

        int stock = await SeedWhenEmptyAsync(connection, transaction, "warehouses", Warehouses, cancellationToken).ConfigureAwait(false);
        stock += await SeedWhenEmptyAsync(connection, transaction, "stock_levels", StockLevels, cancellationToken).ConfigureAwait(false);
        rows += stock;

        rows += await SeedWhenEmptyAsync(connection, transaction, "purchase_orders", PurchaseOrders, cancellationToken).ConfigureAwait(false);
        rows += await SeedWhenEmptyAsync(connection, transaction, "audit_log", AuditLog, cancellationToken).ConfigureAwait(false);
        rows += await SeedIntegrationMessagesAsync(connection, transaction, cancellationToken).ConfigureAwait(false);
        rows += await SeedWhenEmptyAsync(connection, transaction, "sensor_readings", SensorReadings, cancellationToken).ConfigureAwait(false);

        // The populated materialized view is refreshed when what it reads has changed; the one created
        // WITH NO DATA is never refreshed, because being unpopulated is the whole reason it exists.
        if (stock > 0)
        {
            await ExecuteAsync(connection, transaction, "refresh materialized view legacy.stock_by_region", cancellationToken)
                .ConfigureAwait(false);
        }

        rows += await SeedCustomerCreditAsync(connection, transaction, cancellationToken).ConfigureAwait(false);
        rows += await SeedAppSettingsAsync(connection, transaction, cancellationToken).ConfigureAwait(false);

        return rows;
    }

    private static async Task<int> SeedWhenEmptyAsync(
        NpgsqlConnection connection,
        NpgsqlTransaction transaction,
        string table,
        string sql,
        CancellationToken cancellationToken)
    {
        if (await DemoTable.HasRowsAsync(connection, transaction, RelationalDemoSchema.LegacySchemaName, table, cancellationToken)
                .ConfigureAwait(false))
        {
            return 0;
        }

        return await ExecuteAsync(connection, transaction, sql, cancellationToken).ConfigureAwait(false);
    }

    private static async Task<int> ExecuteAsync(
        NpgsqlConnection connection,
        NpgsqlTransaction transaction,
        string sql,
        CancellationToken cancellationToken)
    {
        await using var command = new NpgsqlCommand(sql, connection, transaction);

        // Postgres's own count of inserted and updated rows; the SELECT setval() calls do not add to it.
        return Math.Max(0, await command.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false));
    }

